'use strict';

const crypto = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');

// Names look like dock-<repo>-<shortsha>-<YYYYMMDDTHHMMSS>-<8 hex>.zip. Only files with this
// exact shape inside the managed directory can ever be deleted by the app.
const MANAGED_RE = /^dock-[A-Za-z0-9_-]{1,40}-[0-9a-f]{7,12}-\d{8}T\d{6}-[0-9a-f]{8}\.zip$/;

function pad(n) { return String(n).padStart(2, '0'); }

function newZipName(repoName, sha, now = new Date()) {
  const safeName = String(repoName).replace(/[^A-Za-z0-9_-]/g, '_').slice(0, 40) || 'repo';
  const stamp = `${now.getFullYear()}${pad(now.getMonth() + 1)}${pad(now.getDate())}T${pad(now.getHours())}${pad(now.getMinutes())}${pad(now.getSeconds())}`;
  return `dock-${safeName}-${sha.slice(0, 8)}-${stamp}-${crypto.randomBytes(4).toString('hex')}.zip`;
}

function sameDir(a, b) {
  const norm = (p) => path.resolve(p).toLowerCase();
  return norm(a) === norm(b);
}

function isManagedZip(artifactsDir, filePath) {
  if (typeof filePath !== 'string' || !path.isAbsolute(filePath)) return false;
  return sameDir(path.dirname(filePath), artifactsDir) && MANAGED_RE.test(path.basename(filePath));
}

// Deletes one managed ZIP. Refuses anything outside the artifacts directory, anything whose
// name was not generated by the app, symlinks and non-regular files.
function deleteManagedZip(artifactsDir, filePath) {
  if (!isManagedZip(artifactsDir, filePath)) {
    return { ok: false, error: 'Recusado: o arquivo nao e um ZIP gerenciado pelo ContextDeck.' };
  }
  let stat;
  try { stat = fs.lstatSync(filePath); } catch { return { ok: false, error: 'O ZIP ja nao existe no disco.', missing: true }; }
  if (!stat.isFile()) return { ok: false, error: 'Recusado: o alvo nao e um arquivo regular.' };
  try { fs.unlinkSync(filePath); } catch (error) { return { ok: false, error: `Falha ao excluir: ${error.message}` }; }
  return { ok: true };
}

module.exports = { newZipName, deleteManagedZip };
